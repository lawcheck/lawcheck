"""Отмечен ли чекбокс согласия. Общий для всех форм, собирающих ПДн.

Живёт отдельным модулем, потому что нужен трём независимым роутерам (чат,
оплата, проверка по реестру РКН), а импорт друг из друга их закольцует.
"""


def checked(value: str) -> bool:
    """Пустая строка приходит от снятого поля, но `bool()` здесь мало: строку
    `0` или `false` (скрытое поле-спутник, чужая интеграция) truthiness
    превратила бы в согласие, которого человек не давал."""
    return value.strip().lower() in {"1", "on", "true", "yes", "да"}
