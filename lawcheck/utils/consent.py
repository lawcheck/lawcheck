"""Отмечен ли чекбокс согласия. Общий для всех форм, собирающих ПДн.

Живёт отдельным модулем, потому что нужен независимым роутерам (чат, оплата,
проверка по реестру РКН, регистрация), а импорт друг из друга их закольцует.
"""

# Версия текста /soglasie. Пишется в consent_log с каждым согласием: по ней
# видно, на какую редакцию человек согласился. Правишь soglasie.html – меняй дату.
CONSENT_VERSION = "2026-09-22"


def checked(value: str) -> bool:
    """Пустая строка приходит от снятого поля, но `bool()` здесь мало: строку
    `0` или `false` (скрытое поле-спутник, чужая интеграция) truthiness
    превратила бы в согласие, которого человек не давал."""
    return value.strip().lower() in {"1", "on", "true", "yes", "да"}
