"""Проверка и нормализация email — один вариант на весь проект.

Проверка была размазана по трём местам в виде `"@" in email and "." in ...`.
Она пропускала строку с переводом строки внутри: `"a@b.ru\\nBcc: victim@x.ru"`
её проходит (символ `@` есть, точка в последнем сегменте есть), а дальше адрес
уходит в заголовок `To:` письма и в текст уведомления.
"""
import re

# Практический компромисс, а не RFC 5322: локальная часть без пробелов и
# управляющих символов, домен с хотя бы одной точкой и буквенной зоной.
_EMAIL_RE = re.compile(
    r"^[A-Za-z0-9!#$%&'*+/=?^_`{|}~.-]{1,64}"
    r"@"
    r"(?:[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?\.)+"
    r"[A-Za-z]{2,63}$"
)
_MAX_LEN = 254  # ограничение на адрес целиком (RFC 5321)


def normalize_email(raw: str) -> str:
    """Привести адрес к каноничному виду для хранения и сравнения."""
    return (raw or "").strip().lower()


def valid_email(raw: str) -> bool:
    """Похоже ли это на адрес, которому можно писать.

    Отсекает в том числе управляющие символы: адрес попадает в заголовки письма,
    и перевод строки внутри него — это не «кривой ввод», а инъекция заголовка.
    """
    email = normalize_email(raw)
    if not email or len(email) > _MAX_LEN:
        return False
    if any(ch in email for ch in "\r\n\t\0"):
        return False
    if ".." in email:
        return False
    return bool(_EMAIL_RE.match(email))
